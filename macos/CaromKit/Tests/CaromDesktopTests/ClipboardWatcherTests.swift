import AppKit
import Testing

@testable import CaromDesktop

@MainActor
@Suite struct ClipboardWatcherTests {
    let pb = NSPasteboard(name: NSPasteboard.Name("app.carom.tests.\(UUID().uuidString)"))

    final class Sink { var items: [ClipboardItem] = [] }

    func make() -> (ClipboardWatcher, Sink) {
        let w = ClipboardWatcher(pasteboard: pb)
        let sink = Sink()
        w.onCopy = { sink.items.append($0) }
        w.start()
        return (w, sink)
    }

    func copy(_ text: String, extra: [NSPasteboard.PasteboardType] = []) {
        pb.declareTypes([.string] + extra, owner: nil)
        pb.setString(text, forType: .string)
        for t in extra { pb.setData(Data(), forType: t) }
    }

    @Test func reportsPlainCopy() {
        let (w, sink) = make()
        defer { w.stop() }
        copy("hello")
        w.poll()
        #expect(sink.items == [ClipboardItem(text: "hello", sensitive: false)])
        w.poll()
        #expect(sink.items.count == 1)  // no change, no repeat
    }

    @Test func existingContentAtStartIsIgnored() {
        copy("before")
        let (w, sink) = make()
        defer { w.stop() }
        w.poll()
        #expect(sink.items.isEmpty)
    }

    @Test(arguments: [
        ClipboardWatcher.concealedType, ClipboardWatcher.transientType,
        ClipboardWatcher.autoGeneratedType, ClipboardWatcher.ownWriteType,
    ])
    func skipsMarkedItems(marker: NSPasteboard.PasteboardType) {
        let (w, sink) = make()
        defer { w.stop() }
        copy("secret", extra: [marker])
        w.poll()
        #expect(sink.items.isEmpty)
    }

    @Test func skipsNonText() {
        let (w, sink) = make()
        defer { w.stop() }
        pb.declareTypes([.png], owner: nil)
        pb.setData(Data([1, 2, 3]), forType: .png)
        w.poll()
        #expect(sink.items.isEmpty)
    }

    @Test func skipsOversized() {
        let (w, sink) = make()
        defer { w.stop() }
        copy(String(repeating: "a", count: ClipboardWatcher.maxBytes + 1))
        w.poll()
        #expect(sink.items.isEmpty)
        copy(String(repeating: "a", count: ClipboardWatcher.maxBytes))
        w.poll()
        #expect(sink.items.count == 1)
    }

    @Test func skipsOwnWrites() {
        let (w, sink) = make()
        defer { w.stop() }
        w.write(text: "from phone", sensitive: false)
        w.poll()
        #expect(sink.items.isEmpty)
        #expect(pb.string(forType: .string) == "from phone")
        copy("user copy")
        w.poll()
        #expect(sink.items.map(\.text) == ["user copy"])
    }

    @Test func sensitiveWriteIsConcealed() {
        let w = ClipboardWatcher(pasteboard: pb)
        w.write(text: "pw", sensitive: true)
        #expect(pb.types?.contains(ClipboardWatcher.concealedType) == true)
        #expect(w.readCurrent() == ClipboardItem(text: "pw", sensitive: true))
    }

    @Test func readCurrent() {
        let w = ClipboardWatcher(pasteboard: pb)
        #expect(w.readCurrent() == nil)
        copy("typed")
        #expect(w.readCurrent() == ClipboardItem(text: "typed", sensitive: false))
        copy("hidden", extra: [ClipboardWatcher.concealedType])
        #expect(w.readCurrent() == ClipboardItem(text: "hidden", sensitive: true))
    }
}
