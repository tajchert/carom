import AppKit

public struct ClipboardItem: Sendable, Equatable {
    public var text: String
    public var sensitive: Bool

    public init(text: String, sensitive: Bool) {
        self.text = text
        self.sensitive = sensitive
    }
}

/// Pasteboard access setting for this app (System Settings > Privacy > Paste from Other Apps).
public enum PasteboardAccess: Sendable {
    /// The system default: asks on the first programmatic read.
    case standard
    case ask
    case alwaysAllow
    case alwaysDeny
    /// macOS older than 15.4 cannot report it, and does not prompt either.
    case unknown
}

/// Watches the pasteboard by polling `changeCount` (no notification exists for it).
///
/// Content is never logged. The poll reads text only when access is known not to prompt.
@MainActor
public final class ClipboardWatcher {
    /// Marker type added to our own writes so the watcher skips them.
    nonisolated public static let ownWriteType = NSPasteboard.PasteboardType("app.carom.own-write")
    nonisolated public static let concealedType = NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType")
    nonisolated public static let transientType = NSPasteboard.PasteboardType("org.nspasteboard.TransientType")
    nonisolated public static let autoGeneratedType = NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType")

    /// Texts larger than this (UTF-8 bytes) are not sent. See CLIENTS.md.
    nonisolated public static let maxBytes = 60 * 1024

    public var onCopy: ((ClipboardItem) -> Void)?

    private let pasteboard: NSPasteboard
    private let interval: TimeInterval
    private var timer: Timer?
    private var lastChangeCount: Int

    public init(pasteboard: NSPasteboard = .general, interval: TimeInterval = 0.5) {
        self.pasteboard = pasteboard
        self.interval = interval
        self.lastChangeCount = pasteboard.changeCount
    }

    public var accessBehavior: PasteboardAccess {
        guard #available(macOS 15.4, *) else { return .unknown }
        switch pasteboard.accessBehavior {
        case .default: return .standard
        case .ask: return .ask
        case .alwaysAllow: return .alwaysAllow
        case .alwaysDeny: return .alwaysDeny
        @unknown default: return .standard
        }
    }

    /// Starts polling. Whatever is on the pasteboard now is not reported.
    public func start() {
        stop()
        lastChangeCount = pasteboard.changeCount
        let t = Timer(timeInterval: interval, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.poll() }
        }
        t.tolerance = interval * 0.4  // lets the system coalesce wakeups
        RunLoop.main.add(t, forMode: .common)
        timer = t
    }

    public func stop() {
        timer?.invalidate()
        timer = nil
    }

    /// Writes text and marks it as ours so the watcher does not send it back.
    public func write(text: String, sensitive: Bool) {
        Self.write(text: text, sensitive: sensitive, to: pasteboard)
        lastChangeCount = pasteboard.changeCount
    }

    /// The pasteboard's change count now. Read it right after `write` to remember that write.
    public var changeCount: Int { pasteboard.changeCount }

    /// Empties the pasteboard if nothing was copied since `changeCount` was read, so it still
    /// holds what we wrote. Needs no read of the content, so it never triggers the access prompt.
    /// Returns whether it cleared.
    @discardableResult
    public func clear(ifChangeCount count: Int) -> Bool {
        guard pasteboard.changeCount == count else { return false }
        pasteboard.clearContents()
        lastChangeCount = pasteboard.changeCount
        return true
    }

    /// Writes text and our marker to a pasteboard (also usable without a watcher instance).
    nonisolated public static func write(text: String, sensitive: Bool, to pasteboard: NSPasteboard = .general) {
        var types: [NSPasteboard.PasteboardType] = [.string, ownWriteType]
        if sensitive { types.append(concealedType) }
        pasteboard.declareTypes(types, owner: nil)
        pasteboard.setString(text, forType: .string)
        pasteboard.setData(Data(), forType: ownWriteType)
        if sensitive { pasteboard.setData(Data(), forType: concealedType) }
    }

    /// Explicit, user-initiated read (hotkey, menu item). Ignores the skip markers, because the
    /// user asked for this content. Returns nil for non-text, empty or oversized content.
    public func readCurrent() -> ClipboardItem? {
        let types = Set(pasteboard.types ?? [])
        guard types.contains(.string), let text = pasteboard.string(forType: .string) else { return nil }
        guard Self.isSendable(text) else { return nil }
        return ClipboardItem(text: text, sensitive: types.contains(Self.concealedType))
    }

    // MARK: - Polling

    /// One poll step. Internal so tests can drive it without a timer.
    func poll() {
        let count = pasteboard.changeCount
        guard count != lastChangeCount else { return }
        lastChangeCount = count

        // Only read when it cannot trigger a pasteboard access prompt.
        switch accessBehavior {
        case .alwaysAllow, .unknown: break
        case .standard, .ask, .alwaysDeny: return
        }

        let types = Set(pasteboard.types ?? [])
        guard types.contains(.string) else { return }
        if types.contains(Self.ownWriteType) { return }
        // Automatic mode skips concealed items (password managers). Only an explicit
        // `readCurrent()` can return one, with `sensitive == true`.
        if types.contains(Self.concealedType) || types.contains(Self.transientType)
            || types.contains(Self.autoGeneratedType) { return }

        guard let text = pasteboard.string(forType: .string), Self.isSendable(text) else { return }
        onCopy?(ClipboardItem(text: text, sensitive: false))
    }

    private static func isSendable(_ text: String) -> Bool {
        !text.isEmpty && text.utf8.count <= maxBytes
    }
}
